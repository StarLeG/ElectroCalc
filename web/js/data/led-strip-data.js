export const FEED_SCHEMES = ['one', 'both', 'multi', 'ring'];

/**
 * Коэффициент в формуле просадки на дорожках: ΔU = r · i · L² / k.
 *
 * Питание с одного конца: ток линейно спадает от i·L до нуля, интеграл даёт L²/2.
 * Питание с двух концов: середина — точка нулевого тока, каждая половина ведёт
 * себя как отрезок L/2 с питанием с одного конца, отсюда L²/8, то есть вчетверо
 * меньше. N равномерных точек делят ленту на (N−1) пролётов, питаемых с двух
 * сторон: L²/(8·(N−1)²).
 *
 * @param {string} scheme схема питания
 * @param {number} points число точек питания (для 'multi')
 * @returns {number} делитель k
 */
export function stripDropDivisor(scheme, points) {
  if (scheme === 'one') return 2;
  if (scheme === 'both' || scheme === 'ring') return 8;
  const n = Math.max(2, Math.floor(points) || 2);
  return 8 * (n - 1) ** 2;
}

/**
 * Доля тока ленты, приходящаяся на худший (наиболее нагруженный) провод питания.
 *
 * При питании с одного конца провод несёт весь ток. При питании с двух концов —
 * половину. При N точках внутренняя точка питает два соседних пролёта, крайняя
 * только один, поэтому худшая доля равна 1/(N−1), а не 1/N.
 *
 * @param {string} scheme схема питания
 * @param {number} points число точек питания (для 'multi')
 * @returns {number} доля от полного тока ленты
 */
export function feedCurrentShare(scheme, points) {
  if (scheme === 'one') return 1;
  if (scheme === 'both' || scheme === 'ring') return 0.5;
  const n = Math.max(2, Math.floor(points) || 2);
  return 1 / (n - 1);
}
