'use strict';

/**
 * Границы зоны мгновенного расцепления в кратностях номинального тока.
 *
 * Внутри зоны автомат может сработать, а может и не сработать — стандарт задаёт
 * только её края. Отсюда двойное применение: пуск должен уложиться НИЖЕ нижней
 * границы (иначе автомат имеет право отключиться на каждом пуске), а ток КЗ
 * обязан превысить ВЕРХНЮЮ (иначе отключение не гарантировано).
 */
export const INSTANT_TRIP = { B: [3, 5], C: [5, 10], D: [10, 20] };

/**
 * Характеристика по умолчанию для типа нагрузки.
 * Пользователь может переопределить — выбор остаётся за проектировщиком.
 */
export const CURVE_BY_LOAD = { resistive: 'B', mixed: 'C', motor: 'D' };

/**
 * Запас при проверке отключения при КЗ.
 * Расчётный ток КЗ всегда получается оптимистичнее фактического: сопротивление
 * контактов и нагрев проводника в расчёт не входят.
 */
export const SC_MARGIN = 1.1;

/**
 * Коэффициент I2/In — ток, при котором автомат гарантированно расцепляется
 * в зоне перегрузки (ГОСТ Р 50345, испытательный ток 1,45·In).
 */
export const OVERLOAD_TRIP = 1.45;

/**
 * Ряд номинальных отключающих дифференциальных токов, мА.
 * 6 мА — защита от постоянного тока утечки в зарядных станциях; 10 и 30 мА
 * защищают человека, 100 мА и выше — только от возгорания.
 */
export const RCD_RATINGS = [6, 10, 30, 100, 300, 500];

/**
 * Наименьший номинал УЗО общего применения, мА.
 * 6 мА из ряда сюда не попадает: это устройства защиты от постоянного тока
 * утечки в зарядных станциях, а не аппарат на розеточную группу.
 */
export const RCD_MIN_RATING = 10;

/**
 * Доля допустимой утечки, после которой ждут ложных отключений.
 *
 * Это не норма, а практика: у самого предела ПУЭ сеть уже «шумит» утечкой,
 * и добавки от сырости или длинной трассы хватает на ложное срабатывание.
 */
export const NUISANCE_THRESHOLD = 0.8;

/** Ряд номинальных токов УЗО и дифавтоматов, А. */
export const RCD_NOMINAL_CURRENTS = [16, 25, 40, 63, 80, 100, 125];

/** Ряд отключающей способности бытовых аппаратов, А. */
export const BREAKING_CAPACITY = [4500, 6000, 10000];

/**
 * Ток утечки при отсутствии данных об электроприёмниках, ПУЭ 7.1.83:
 * 0,4 мА на 1 А тока нагрузки и 10 мкА на 1 м длины фазного проводника.
 */
export const LEAKAGE = { perAmp: 0.4, perMetre: 0.01 };

/**
 * Кратность запаса по току утечки, ПУЭ 7.1.83: суммарный ток утечки сети в
 * нормальном режиме не должен превышать 1/3 номинального тока УЗО.
 */
export const LEAKAGE_MARGIN = 3;

/**
 * Предельный номинальный отключающий дифференциальный ток по назначению линии.
 *
 * Это ПОТОЛОК, а не результат расчёта: УЗО с током больше 30 мА человека уже
 * не защищает, оно противопожарное. Когда расчёт по ПУЭ 7.1.83 требует больше
 * потолка, поднимать номинал нельзя — линию делят на группы.
 */
export const RCD_LIMITS = {
  wet: 10,     // ванные, душевые, бассейны, детские — повышенная опасность
  group: 30,   // розеточные группы и бытовые потребители
  main: 300,   // ввод в здание, противопожарное УЗО
};

/**
 * Тип УЗО по характеру тока утечки, который создаёт нагрузка.
 *
 * Тип реагирует не на величину утечки, а на её форму: обычное УЗО типа AC
 * видит только синусоиду и «слепнет» от постоянной составляющей, которую даёт
 * выпрямитель импульсного блока питания.
 */
export const RCD_TYPE_BY_LOAD = {
  resistive: 'AC',    // ТЭНы, лампы накаливания — утечка синусоидальная
  electronics: 'A',   // импульсные блоки питания, бытовая техника, светодиоды
  drive1ph: 'F',      // однофазные частотные приводы, инверторные машины
  drive3ph: 'B',      // трёхфазные приводы, зарядные станции, солнечные инверторы
};

/**
 * Минимальная кратность номиналов смежных ступеней УЗО.
 * Вместе с задержкой у вышестоящего аппарата даёт селективность: при утечке
 * в группе отключается групповое УЗО, а не вводное.
 */
export const SELECTIVITY_RATIO = 3;

/** Исполнения УЗО с выдержкой времени — только они годятся на верхнюю ступень. */
export const DELAYED_RCD_TYPES = ['S', 'G'];
